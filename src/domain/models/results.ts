export interface YearProjection {
  year: number
  age: number
  expenses: number
  earnedIncome: number       // active salary / business income earned this year
  otherIncome: number        // pension, rent, lump sums
  totalIncome: number        // earnedIncome + otherIncome
  netSavings: number         // surplus invested into portfolio (Income - Expenses if positive)
  netWithdrawal: number      // deficit withdrawn from portfolio (Expenses - Income if positive)
  investmentGrowth: number
  openingCorpus: number
  closingCorpus: number
}

export interface LifestyleComparison {
  lifestyle: 'bare_minimum' | 'comfortable' | 'luxury'
  label: string
  description: string
  monthlyExpenseToday: number
  totalLifetimeCostOfLiving: number
  requiredCorpus: number
  peakCorpus: number
  peakAge: number
}

export interface ScenarioResult {
  label: string
  inflationRate: number
  returnRate: number
  currentAnnualExpense: number
  currentMonthlyEquivalent: number
  essentialAnnualExpense: number
  discretionaryAnnualExpense: number
  totalLifetimeExpenses: number          // Total sum of all inflated expenses over entire lifetime
  totalLifetimeIncome: number            // Total sum of all earned & other income
  totalLifetimeSavingsInvested: number   // Total career surplus invested into corpus
  totalLifetimeWithdrawals: number       // Total deficit withdrawn from corpus
  totalLifetimeInvestmentGrowth: number  // Total investment returns generated by compounding
  requiredCorpus: number
  peakCorpus: number
  peakCorpusAge: number
  totalAccumulatedSavings: number
  depletionAge?: number
  existingCorpus: number
  fundingGap: number
  safetyMarginAmount: number
  corpusWithSafetyMargin: number
  yearProjections: YearProjection[]
}

export interface CalculationResults {
  scenarios: ScenarioResult[]
  lifestyleComparisons: LifestyleComparison[]
  warnings: string[]
  calculatedAt: string
}
